#!/usr/bin/env node
/**
 * skill-size.mjs — the SKILL.md budget gate. A skill's SKILL.md loads whole into
 * the session on every use, so a skill that grows with every release dilutes the
 * attention its own instructions get: the largest went from ~150 to 211 lines
 * between 0.36 and 0.39 with nothing to stop 250. CODESTYLE §10 caps code files
 * at 500 lines for the same reason; the cap here is lower because nothing else
 * reloads on every invocation. A skill that outgrows its cap moves detail into
 * references/ (precedent: brainstorm/references/ears-patterns.md).
 *
 * Also: every relative markdown link in a SKILL.md must resolve to a file. Nothing
 * else in the repository imports a SKILL.md, so a link left pointing at a moved
 * reference or a deleted script ships green. Links inside fenced code blocks are
 * templates the skill tells its reader to write elsewhere (tech-writer's
 * screenshot placeholder), not links this repository owes — not checked.
 *
 * Checks skills/<name>/SKILL.md and the mirrored roles/<role>/skills/<name>/SKILL.md
 * (the role trees are regenerated by compliance --fix and pass the same gate):
 *   1. Budget — at most 220 lines and 13*1024 UTF-8 bytes per SKILL.md.
 *   2. Local links — every [text](target) with no URL scheme exists on disk.
 *
 * Exit codes: 0 — clean, 1 — findings.
 * Run: node scripts/skill-size.mjs (also part of npm test)
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const MAX_LINES = 220;
export const MAX_BYTES = 13 * 1024;

/**
 * Fenced code blocks cut out of a SKILL.md. A link inside a fence is part of a
 * template the skill instructs its reader to write in another document, not a
 * link this repository owes. Both fence kinds are honored; an unclosed fence
 * swallows the rest of the file — acceptable here, as the fail-safe direction
 * (checking fewer links, not reporting false ones).
 * @param {string} text
 * @returns {string}
 */
export function stripFences(text) {
  let openMarker = null; // "```" or "~~~" — a fence closes only on its own marker
  const out = [];
  for (const line of String(text ?? "").split("\n")) {
    const m = /^(```|~~~)/.exec(line);
    if (m) {
      openMarker = openMarker === m[1] ? null : openMarker ?? m[1];
    } else if (!openMarker) {
      out.push(line);
    }
  }
  return out.join("\n");
}

/**
 * Relative markdown link targets of a fences-stripped SKILL.md: the target of
 * every [text](target), with the #anchor dropped and scheme links (http, mailto)
 * skipped — they leave the repository and are not ours to check.
 * @param {string} text
 * @returns {string[]}
 */
export function localLinks(text) {
  const targets = [];
  for (const m of String(text ?? "").matchAll(/\]\(([^)\s]+)\)/g)) {
    const target = m[1].split("#")[0];
    if (!target || /^[a-z][a-z0-9+.-]*:/i.test(target)) continue;
    targets.push(target);
  }
  return targets;
}

/**
 * Budget findings of one SKILL.md, as detail lines without the file name
 * (the caller prefixes it) — empty when within budget.
 * @param {string} text
 * @returns {string[]}
 */
export function budgetFindings(text) {
  const findings = [];
  const lines = String(text ?? "").split("\n").length;
  if (lines > MAX_LINES) {
    findings.push(`${lines} lines (budget ${MAX_LINES}) — move detail into references/`);
  }
  const bytes = Buffer.byteLength(text, "utf8");
  if (bytes > MAX_BYTES) {
    findings.push(`${bytes} UTF-8 bytes (budget ${MAX_BYTES}) — move detail into references/`);
  }
  return findings;
}

/**
 * Link findings of one SKILL.md against the disk, detail lines without the file
 * name — empty when every local target exists.
 * @param {string} absPath — the SKILL.md file, links resolve from its directory.
 * @returns {string[]}
 */
export function linkFindings(absPath) {
  const text = readFileSync(absPath, "utf8");
  return localLinks(stripFences(text))
    .filter((target) => !existsSync(resolve(dirname(absPath), target)))
    .map((target) => `link target "${target}" does not exist`);
}

/** The SKILL.md files to check: the plugin tree and the mirrored role trees.
 *  @param {string} rootDir @returns {string[]} repo-relative, forward slashes. */
export function skillFiles(rootDir) {
  const out = [];
  const push = (skillDir, prefix) => {
    const md = join(skillDir, "SKILL.md");
    if (existsSync(md)) out.push(prefix + "SKILL.md");
  };
  for (const name of readdirSync(join(rootDir, "skills"))) {
    push(join(rootDir, "skills", name), `skills/${name}/`);
  }
  const roles = join(rootDir, "roles");
  if (existsSync(roles)) {
    for (const role of readdirSync(roles)) {
      const dir = join(roles, role, "skills");
      if (!existsSync(dir)) continue;
      for (const name of readdirSync(dir)) {
        push(join(dir, name), `roles/${role}/skills/${name}/`);
      }
    }
  }
  return out.sort();
}

async function main() {
  const root = fileURLToPath(new URL("..", import.meta.url));
  const findings = [];
  let count = 0;
  for (const rel of skillFiles(root)) {
    count++;
    const abs = join(root, rel);
    findings.push(...budgetFindings(readFileSync(abs, "utf8")).map((d) => `${rel}: ${d}`));
    findings.push(...linkFindings(abs).map((d) => `${rel}: ${d}`));
  }
  if (findings.length) {
    process.stdout.write(findings.map((f) => `- ${f}`).join("\n") + `\n${findings.length} finding(s)\n`);
    process.exit(1);
  }
  process.stdout.write(`skill-size: ${count} SKILL.md within budget, local links resolve\n`);
}

// The script runs both as a CLI and as an import in tests — main() only when executed.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
